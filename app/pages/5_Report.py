"""Report Page — Atlas Copco Market Scout.

Allows operators to preview run contents, select report formats (PPTX or PDF),
generate executive slide decks and digests, and download report binaries
in-memory with zero local disk writes.
"""

from __future__ import annotations

import streamlit as st

from app.lib.data import (
    StorageAccessError,
    get_active_prefix,
    is_demo_prefix,
    latest_run_id,
    list_run_ids,
    load_envelope,
)
from app.lib.report import (
    FORMAT_LABELS,
    extract_report_preview_metrics,
    find_existing_reports,
    generate_report_bytes,
    get_report_filename,
    get_report_mime_type,
)
from atlas import storage


def main() -> None:
    st.set_page_config(
        page_title="Executive Reports — Atlas Copco Market Scout",
        page_icon="📑",
        layout="wide",
    )

    st.title("📑 Executive Intelligence Reports")
    st.caption("Generate, preview, and export board-ready PowerPoint presentations and PDF digests.")

    # 1. Environment & Storage Notice
    prefix = get_active_prefix()
    st.sidebar.markdown(f"**Storage Prefix:** `{prefix or '(root / demo)'}`")
    if is_demo_prefix():
        st.sidebar.warning(
            "⚠️ **Live Demo Mode:** `ATLAS_PATH_PREFIX` is empty. You are connected to primary demo storage."
        )
    else:
        st.sidebar.info(f"Connected to sandbox prefix: `{prefix}`")

    # 2. Run Selection
    try:
        run_ids = list_run_ids()
    except Exception as exc:
        st.error(f"❌ Failed to list runs from cloud storage: {exc}")
        return

    if not run_ids:
        st.info(
            "💡 **No runs available:** No pipeline runs detected in Volume storage. "
            "Execute a run using the **Run Launcher (4_Run)** before generating reports."
        )
        return

    latest_id = latest_run_id() or run_ids[0]
    selected_run_id = st.sidebar.selectbox(
        "Select Pipeline Run",
        options=run_ids,
        index=0,
        help="Choose the run whose extracted intelligence will populate the report.",
    )

    st.sidebar.divider()
    st.sidebar.caption("Reports are generated in-memory • Zero local file footprint")

    # 3. Load Selected Envelope for Preview
    try:
        envelope = load_envelope(selected_run_id)
        metrics = extract_report_preview_metrics(envelope)
    except StorageAccessError as err:
        st.error(f"❌ Storage access error reading envelope for `{selected_run_id}`: {err}")
        return
    except ValueError as err:
        st.error(f"❌ Envelope validation error for `{selected_run_id}`: {err}")
        return

    # 4. Report Preview Summary Card
    st.subheader(f"📊 Content Preview for Run `{selected_run_id}`")
    st.markdown(
        f"**Scope:** {metrics['scope_tech']} | **Region:** {metrics['scope_region']} | "
        f"**Publication Window:** {metrics['date_range']}"
    )

    mcol1, mcol2, mcol3, mcol4, mcol5 = st.columns(5)
    with mcol1:
        st.metric("Sources Checked", metrics["sources_count"])
    with mcol2:
        st.metric("Verified Items", metrics["items_count"])
    with mcol3:
        st.metric("Story Clusters", metrics["stories_count"], help=f"{metrics['multi_source_stories_count']} stories seen in multiple sources")
    with mcol4:
        st.metric("Discovered Sources", metrics["candidates_considered"])
    with mcol5:
        st.metric("Fallback Items", metrics["fallback_items_count"], help="Items collected from alternative sources when a competitor site was refused")

    if metrics["top_companies"]:
        st.caption(f"**Key Companies Covered:** {', '.join(metrics['top_companies'])}")

    st.divider()

    # 5. Format Selection & Report Generation
    st.subheader("🛠️ Generate New Report")

    col_fmt, col_btn = st.columns([2, 1])

    with col_fmt:
        format_choice = st.radio(
            "Select Output Format",
            options=["pptx", "pdf"],
            format_func=lambda f: FORMAT_LABELS.get(f, f.upper()),
            index=0,
            horizontal=True,
            help="PPTX delivers 16:9 widescreen executive slides; PDF delivers a compact executive digest document.",
        )

    with col_btn:
        st.markdown("<div style='height: 28px;'></div>", unsafe_allow_html=True)
        generate_clicked = st.button("🚀 Generate Executive Report", type="primary", use_container_width=True)

    # Store newly generated bytes in session state
    state_key = f"generated_report_{selected_run_id}_{format_choice}"

    if generate_clicked:
        with st.spinner(f"Building {format_choice.upper()} report and uploading to Databricks Volume..."):
            report_bytes, err_msg = generate_report_bytes(selected_run_id, format_choice)

            if err_msg:
                st.error(f"❌ {err_msg}")
            elif report_bytes:
                st.session_state[state_key] = report_bytes
                st.success(
                    f"🎉 Successfully generated {format_choice.upper()} report for run `{selected_run_id}`! "
                    f"Uploaded to `reports/report_{selected_run_id}.{format_choice}` in Volume."
                )

    # If newly generated report exists in session state, show instant download button
    if state_key in st.session_state:
        st.download_button(
            label=f"📥 Download Generated {format_choice.upper()} Report",
            data=st.session_state[state_key],
            file_name=get_report_filename(selected_run_id, format_choice),
            mime=get_report_mime_type(format_choice),
            type="primary",
            use_container_width=False,
        )

    st.divider()

    # 6. Existing Reports in Cloud Volume
    st.subheader(f"📂 Available Reports in Cloud Volume (`reports/`)")

    try:
        volume_entries = storage.list_dir("reports")
    except Exception:
        volume_entries = []

    matching_reports = find_existing_reports(selected_run_id, volume_entries)

    if matching_reports:
        for rep in matching_reports:
            rcol1, rcol2 = st.columns([3, 1])
            with rcol1:
                icon = "📊" if rep["fmt"] == "pptx" else "📄"
                st.markdown(f"**{icon} {rep['label']}** (`{rep['filename']}`)")
                st.caption(f"Cloud Path: `{rep['relative_path']}`")
            with rcol2:
                try:
                    data_bytes = storage.read_bytes(rep["relative_path"])
                    st.download_button(
                        label=f"📥 Download ({rep['fmt'].upper()})",
                        data=data_bytes,
                        file_name=rep["filename"],
                        mime=rep["mime_type"],
                        key=f"dl_{rep['filename']}",
                        use_container_width=True,
                    )
                except Exception as dl_err:
                    st.error(f"Failed to read report: {dl_err}")
    else:
        st.info(f"No existing reports found in cloud storage for run `{selected_run_id}`. Generate one above!")

    st.divider()
    st.caption("🔒 **Zero Local Data Footprint:** Reports are created in-memory, uploaded directly to Databricks Volume, and streamed to your browser via memory buffers.")


if __name__ == "__main__":
    main()
